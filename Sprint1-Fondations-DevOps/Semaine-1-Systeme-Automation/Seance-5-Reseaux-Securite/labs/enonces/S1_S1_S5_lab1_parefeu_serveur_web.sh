echo ""
echo "Tâche 2.3: Vérifier la configuration des politiques"
echo "  Commande: sudo ufw status verbose"
echo ""

echo "ÉTAPE 3: Configuration de l'accès SSH sécurisé"
echo "--------------------------------------------"
echo "Tâche 3.1: Autoriser SSH sur port non-standard"
echo "  Objectif: Sécuriser l'administration à distance"
echo "  Port cible: 2222 (évite les scans automatiques sur 22)"
echo "  Commande à exécuter: sudo ufw allow 2222/tcp comment 'SSH Admin'"
echo ""
echo "Tâche 3.2: Restriction par réseau source (BONUS)"
echo "  Si vous connaissez votre réseau d'administration:"
echo "  Exemple: sudo ufw allow from 192.168.1.0/24 to any port 2222"
echo "  Remplacez 192.168.1.0/24 par votre réseau réel"
echo ""

echo "ÉTAPE 4: Configuration des services web"
echo "-------------------------------------"
echo "Tâche 4.1: Autoriser le trafic HTTP"
echo "  Objectif: Permettre l'accès au site web"
echo "  Commande à exécuter: sudo ufw allow 80/tcp comment 'HTTP Web'"
echo ""
echo "Tâche 4.2: Autoriser le trafic HTTPS"
echo "  Objectif: Permettre l'accès sécurisé au site"
echo "  Commande à exécuter: sudo ufw allow 443/tcp comment 'HTTPS Web'"
echo ""
echo "Tâche 4.3: Alternative avec profils d'applications"
echo "  Commande: sudo ufw app list"
echo "  Si disponible: sudo ufw allow 'Apache Full'"
echo "  Ou: sudo ufw allow 'Nginx Full'"
echo ""

echo "ÉTAPE 5: Activation et validation"
echo "------------------------------"
echo "Tâche 5.1: Activer le pare-feu UFW"
echo "  ATTENTION: Assurez-vous d'avoir autorisé SSH avant !"
echo "  Commande à exécuter: sudo ufw enable"
echo "  Réponse attendue: 'y' pour confirmer"
echo ""
echo "Tâche 5.2: Vérifier la configuration finale"
echo "  Commande: sudo ufw status numbered"
echo "  Question: Combien de règles sont actives ?"
echo ""
echo "Tâche 5.3: Tester la connectivité"
echo "  SSH: Connexion sur port 2222"
echo "  Web: curl http://localhost (si service installé)"
echo ""

echo "ÉTAPE 6: Tests de sécurité et validation"
echo "--------------------------------------"
echo "Tâche 6.1: Tester les connexions autorisées"
echo "  Test SSH: ssh -p 2222 utilisateur@serveur"
echo "  Test HTTP: curl -I http://adresse-serveur"
echo "  Test HTTPS: curl -I https://adresse-serveur"
echo ""
echo "Tâche 6.2: Vérifier le blocage des ports non autorisés"
echo "  Test d'un port fermé: telnet adresse-serveur 25"
