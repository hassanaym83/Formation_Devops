echo "----------------------------------------------"
echo "Tâche 2.1: Définir la politique de refus par défaut"
echo "  Objectif: Bloquer tout trafic entrant non autorisé"
echo "  Commande à exécuter: sudo ufw default deny incoming"
echo ""
echo "Tâche 2.2: Autoriser le trafic sortant"
echo "  Objectif: Permettre les connexions sortantes (mises à jour, etc.)"
