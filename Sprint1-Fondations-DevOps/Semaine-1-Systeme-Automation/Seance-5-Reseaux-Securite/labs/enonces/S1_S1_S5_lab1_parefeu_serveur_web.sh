echo "4. □ HTTP autorisé sur port 80"
echo "5. □ HTTPS autorisé sur port 443"
echo "6. □ Connectivité SSH fonctionnelle"
echo "7. □ Autres ports bloqués par défaut"
echo ""

echo "Questions de compréhension:"
echo "Q1: Pourquoi utiliser le port 2222 au lieu de 22 pour SSH ?"
